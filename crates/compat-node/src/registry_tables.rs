//! Data tables for the builtin registry: each public builtin with its export list, and the JS
//! factory source behind each module name. Pure data; the logic lives in `registry.rs`.

/// A public builtin and its named exports (everything except `default`).
pub struct Builtin {
    pub name: &'static str,
    pub exports: &'static [&'static str],
}

impl Builtin {
    pub const fn new(name: &'static str, exports: &'static [&'static str]) -> Self {
        Self { name, exports }
    }
}

