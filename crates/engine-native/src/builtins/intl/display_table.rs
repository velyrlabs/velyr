/// The English or Portuguese name for `code`.
pub(super) fn lookup(table: &[Row], code: &str, portuguese: bool) -> Option<&'static str> {
    let (_, en, pt) = table.iter().find(|(known, ..)| *known == code)?;
    Some(if portuguese { pt } else { en })
}
